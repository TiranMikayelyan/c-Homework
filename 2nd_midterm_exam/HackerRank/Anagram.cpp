int makeAnagram(string a, string b) {
    if (a == b)                  // եթե երկու string-ները նույնն են
        return 0;                // ջնջելու բան չկա

    int count[26] = {0};         // array՝ a–z տառերի քանակը պահելու համար

    for (int i = 0; i < a.length(); i++) {   // անցնում ենք a string-ի բոլոր տառերով
        int index = a[i] - 'a';               // տառը փոխում ենք index-ի (a=0, b=1, ...)
        count[index]++;                       // տվյալ տառի քանակը մեկով ավելացնում ենք
    }

    for (int i = 0; i < b.length(); i++) {   // անցնում ենք b string-ի բոլոր տառերով
        int index = b[i] - 'a';               // տառը փոխում ենք index-ի
        count[index]--;                       // տվյալ տառի քանակը մեկով պակասեցնում ենք
    }

    int del_count = 0;                        // ընդհանուր ջնջվող տառերի քանակը
    for (int i = 0; i < 26; i++) {            // անցնում ենք բոլոր 26 տառերով
        if (count[i] > 0)                     // եթե տարբերությունը դրական է
            del_count += count[i];             // ավելացնում ենք այդ քանակը
        else                                  // եթե տարբերությունը բացասական է
            del_count -= count[i];             // դարձնում ենք դրական ու գումարում
    }

    return del_count;                         // վերադարձնում ենք նվազագույն ջնջումների քանակը
}
